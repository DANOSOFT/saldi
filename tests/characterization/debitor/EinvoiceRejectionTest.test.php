    /** KMD answers "no postbox" even when a CVR is missing too; it must never read as a CVR problem. */
    public function testTheKmdPostboxErrorWinsOverAMissingCvr(): void
    {
        $r = einvoice_classify_message('[DK-R-017] ... GLN:5798009280145 is not a KMD customer. It has no postbox purchase.');
