    /** EasyUBL's text is shown on the order page, so markup in it must arrive as text. */
    public function testTheNoticeEscapesTheMessage(): void
    {
        $html = einvoiceRejectionHtml(
            ['status' => 'Error', 'message' => '<script>alert(1)</script> O\'Brien', 'class' => 'cvr_missing', 'created' => '2026-10-30 09:15:00'],
            ['title' => 'E-fakturaen blev afvist', 'message' => 'Besked', 'cvr_missing' => 'Mangler CVR']
        );
        self::assertStringNotContainsString('<script>', $html);
        self::assertStringContainsString('&lt;script&gt;alert(1)&lt;/script&gt; O&#039;Brien', $html);
        self::assertStringContainsString('Mangler CVR', $html);
        self::assertStringContainsString('30-10-2026 09:15', $html);
    }

    public function testAnUnknownRejectionShowsOnlyTheMessage(): void
    {
        $html = einvoiceRejectionHtml(
            ['status' => 'Rejected', 'message' => 'Something else', 'class' => 'unknown', 'created' => ''],
            ['title' => 'E-fakturaen blev afvist', 'message' => 'Besked', 'cvr_missing' => 'Mangler CVR']
        );
        self::assertStringContainsString('Something else', $html);
        self::assertStringNotContainsString('Mangler CVR', $html);
    }

    /** @return array<string, mixed> */
    private static function runChild(string $script): array
    {
        $process = proc_open([PHP_BINARY, __DIR__ . '/support/' . $script], [1 => ['pipe', 'w'], 2 => ['pipe', 'w']], $pipes);
        self::assertIsResource($process);
        $out = stream_get_contents($pipes[1]);
        $err = stream_get_contents($pipes[2]);
        fclose($pipes[1]);
        fclose($pipes[2]);
        self::assertSame(0, proc_close($process), $out . $err);
        $decoded = json_decode((string) $out, true);
        self::assertIsArray($decoded, $out . $err);
        return $decoded;
    }

    /** The webhook's invoice number and EasyUBL's text are escaped, and the row carries the class. */
    public function testTheWebhookStoresTheMessageEscaped(): void
    {
        $r = self::runChild('einvoice_events_sql.php')['webhook'];
        self::assertTrue($r['written']);
        $lookup = implode("\n", array_filter($r['sql'], fn ($s) => strpos($s, 'FROM ordrer') !== false));
        self::assertStringContainsString("fakturanr = '1042'' OR ''1''=''1'", $lookup);
        $insert = (string) end($r['sql']);
        self::assertStringStartsWith('INSERT INTO einvoice_events', $insert);
        self::assertStringContainsString("'webhook', 'Error'", $insert);
        self::assertStringContainsString("(O''Brien)", $insert);
        self::assertStringContainsString("'cvr_missing'", $insert);
        self::assertStringContainsString('VALUES (42,', $insert);
    }

    public function testAnInvoiceNumberNobodyHasWritesNothing(): void
    {
        $r = self::runChild('einvoice_events_sql.php')['unknown_invoice'];
        self::assertFalse($r['written']);
        self::assertEmpty(array_filter($r['sql'], fn ($s) => strpos($s, 'INSERT') === 0));
    }

    /** A failed send with a CVR on the invoice is a rejection, but not one a CVR fixes. */
    public function testAFailedSendIsStored(): void
    {
        $r = self::runChild('einvoice_events_sql.php')['send'];
        self::assertTrue($r['written']);
        $insert = (string) end($r['sql']);
        self::assertStringContainsString("'send', 'SendFailed'", $insert);
        self::assertStringContainsString("'receiver_rejected'", $insert);
    }

    /** Before the update has run, nothing is written and nothing is created. */
    public function testWithoutTheTableNothingIsWrittenOrCreated(): void
    {
        $r = self::runChild('einvoice_events_no_table.php');
        self::assertFalse($r['webhook']);
        self::assertFalse($r['send']);
        self::assertNull($r['latest']);
        foreach ($r['sql'] as $sql) {
            self::assertDoesNotMatchRegularExpression('/^\s*(INSERT|CREATE|ALTER)/i', $sql);
        }
    }
