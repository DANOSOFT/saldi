require_once __DIR__ . '/../../includes/std_func.php';

final class RequestId
{
    private static $id;

    /** UUID syntax (any version); invalid client values are replaced with a UUID v4. */
    public static function resolve(?string $candidate): string
    {
        if ($candidate !== null && preg_match('/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/iD', $candidate)) {
            return $candidate;
        }
        $bytes = random_bytes(16);
        $bytes[6] = chr((ord($bytes[6]) & 0x0f) | 0x40);
        $bytes[8] = chr((ord($bytes[8]) & 0x3f) | 0x80);
        $hex = bin2hex($bytes);
        return substr($hex, 0, 8) . '-' . substr($hex, 8, 4) . '-' . substr($hex, 12, 4)
            . '-' . substr($hex, 16, 4) . '-' . substr($hex, 20);
    }

    /** One id shared by bootstrap, CORS, endpoint and log. */
    public static function current(): string
    {
        if (self::$id === null) {
            self::$id = self::resolve(ifset($_SERVER, 'HTTP_X_REQUEST_ID'));
        }
        return self::$id;
    }

    /** Echo even for preflight and bootstrap failures. */
    public static function emit(): void
    {
        header('X-Request-Id: ' . self::current());
    }
}
